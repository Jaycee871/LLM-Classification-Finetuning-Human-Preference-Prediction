"""Regenerate the Kaggle offline GPU notebook's embedded source cell.

Run after editing src/baseline.py, src/finetune_lora.py or src/length_baseline.py:
    python scripts/sync_gpu_notebook.py

CI compares the generated cell against checked-in notebook source.
This keeps scoring-time execution offline while preventing code drift.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NOTEBOOK = ROOT / "notebooks" / "kaggle_gpu_lora_pilot.ipynb"
MODULES = ("baseline.py", "finetune_lora.py", "length_baseline.py")
HEADER = "# Generated by python scripts/sync_gpu_notebook.py; do not edit this cell by hand.\n"


def generated_source_cell():
    lines = [
        HEADER,
        "from pathlib import Path\n",
        "import sys\n",
        "source_dir = Path('/kaggle/working/src')\n",
        "source_dir.mkdir(parents=True, exist_ok=True)\n",
        "(source_dir / '__init__.py').write_text('', encoding='utf-8')\n",
    ]
    for filename in MODULES:
        source = (ROOT / "src" / filename).read_text(encoding="utf-8")
        # A JSON string literal is a valid Python string literal for these files.
        payload = json.dumps(source, ensure_ascii=True)
        lines.append(
            f"(source_dir / {filename!r}).write_text({payload}, encoding='utf-8')\n"
        )
    lines.extend([
        "sys.path.insert(0, '/kaggle/working')\n",
        "from src.finetune_lora import train_and_predict\n",
    ])
    return lines


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="Return nonzero if the committed cell is out of sync")
    args = parser.parse_args()

    notebook = json.loads(NOTEBOOK.read_text(encoding="utf-8"))
    assert notebook["cells"][2]["cell_type"] == "code", "Unexpected notebook layout"
    expected = generated_source_cell()
    if args.check:
        if notebook["cells"][2]["source"] != expected:
            raise SystemExit(
                "Offline Kaggle notebook is stale: "
                "run python scripts/sync_gpu_notebook.py"
            )
        print("GPU Notebook source is synchronized.")
        return
    notebook["cells"][2]["source"] = expected
    NOTEBOOK.write_text(
        json.dumps(notebook, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"Synchronized: {NOTEBOOK.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
