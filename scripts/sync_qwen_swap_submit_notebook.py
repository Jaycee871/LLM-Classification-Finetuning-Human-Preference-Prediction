"""Synchronize the Qwen 1024 swap-ensemble submission Notebook."""
import argparse,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
NOTEBOOK=ROOT/"notebooks"/"qwen_swap_ensemble_submission.ipynb"
MODULES=("baseline.py","qwen_swap_ensemble.py","qwen_swap_submit_1024.py")
HEADER="# Generated by python scripts/sync_qwen_swap_submit_notebook.py; do not edit this cell by hand.\n"

def generated_source_cell():
    lines=[HEADER,"from pathlib import Path\n","import sys\n","source_dir=Path('/kaggle/working/src')\n","source_dir.mkdir(parents=True,exist_ok=True)\n","(source_dir/'__init__.py').write_text('',encoding='utf-8')\n"]
    for filename in MODULES:
        content=(ROOT/"src"/filename).read_text(encoding="utf-8")
        lines.append(f"(source_dir/{filename!r}).write_text("+json.dumps(content,ensure_ascii=True)+",encoding='utf-8')\n")
    lines.extend(["sys.path.insert(0,'/kaggle/working')\n","from src.qwen_swap_submit_1024 import run\n"])
    return lines

if __name__=="__main__":
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--check",action="store_true")
    a=p.parse_args()
    nb=json.loads(NOTEBOOK.read_text(encoding="utf-8"))
    expected=generated_source_cell()
    if a.check:
        if nb["cells"][2]["source"]!=expected:
            raise SystemExit("Swap submission Notebook stale. Run python scripts/sync_qwen_swap_submit_notebook.py")
        print("Swap submission Notebook matches source modules.")
    else:
        nb["cells"][2]["source"]=expected
        NOTEBOOK.write_text(json.dumps(nb,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
        print("Regenerated swap submission Notebook.")
