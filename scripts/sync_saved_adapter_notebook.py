"""Synchronize an offline Kaggle Notebook against authoritative project modules."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NOTEBOOK = ROOT / "notebooks" / "diagnose_saved_qwen_adapter.ipynb"
MODULES = ("baseline.py", "finetune_lora.py", "length_baseline.py", "saved_adapter_inference.py")
HEADER = "# Generated by python scripts/sync_saved_adapter_notebook.py; do not edit this cell by hand.\n"


def generated_source_cell():
    lines = [
        HEADER, "from pathlib import Path\n", "import sys\n",
        "source_dir = Path('/kaggle/working/src')\n",
        "source_dir.mkdir(parents=True, exist_ok=True)\n",
        "(source_dir / '__init__.py').write_text('', encoding='utf-8')\n",
    ]
    for filename in MODULES:
        source = (ROOT / "src" / filename).read_text(encoding="utf-8")
        lines.append(
            f"(source_dir / {filename!r}).write_text("
            + json.dumps(source, ensure_ascii=True)
            + ", encoding='utf-8')\n"
        )
    lines.extend([
        "sys.path.insert(0, '/kaggle/working')\n",
        "from src.saved_adapter_inference import main\n",
    ])
    return lines


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    notebook = json.loads(NOTEBOOK.read_text(encoding="utf-8"))
    expected = generated_source_cell()
    if args.check:
        if notebook["cells"][2]["source"] != expected:
            raise SystemExit("Saved-adapter Notebook stale. Run python scripts/sync_saved_adapter_notebook.py")
        print("Saved-adapter Notebook code matches all authoritative modules.")
    else:
        notebook["cells"][2]["source"] = expected
        NOTEBOOK.write_text(json.dumps(notebook, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print("Regenerated offline saved-adapter Notebook.")
